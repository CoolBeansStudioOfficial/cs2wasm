// What cs2wasm changes of the upstream sources it compiles (SPEC 7.5, docs/AUDIT.md A5.15 and step 13.5), written to
// docs/UPSTREAM.md so the boundary can be audited:
//   - per library, the exact edits and the replaced files its manifest lists (src/Cs2Wasm/Upstream/<Library>/
//     manifest.txt), each with the reason tools/CoreLibManifest gives for it (the comment above the line that writes it);
//   - System.Private.CoreLib's runtime half (Mono's, src/mono/System.Private.CoreLib/src in dotnet/runtime), which
//     cs2wasm supplies against its own runtime: each file the same as upstream, changed (how many lines, and the
//     comments marked cs2wasm that say why), or cs2wasm's own.
// usage: node tools/upstream-report.mjs [runtime-root]   (default: %LOCALAPPDATA%/cs2wasm/runtime-v11.0.0)
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const runtime = process.argv[2] ?? join(process.env.LOCALAPPDATA ?? '', 'cs2wasm', 'runtime-v11.0.0');
if (!existsSync(join(runtime, 'src', 'mono'))) { console.error('no dotnet/runtime sources at ' + runtime); process.exit(2); }
const upstream = join(root, 'src', 'Cs2Wasm', 'Upstream');
const lf = (s) => s.replace(/\r\n/g, '\n');
const out = [];
const w = (s = '') => out.push(s);

// the reasons: tools/CoreLibManifest's comments above the lines that write each edit or replacement
const gen = lf(readFileSync(join(root, 'tools', 'CoreLibManifest', 'Program.cs'), 'utf8')).split('\n');
function reasonFor(path, text) {
  const i = gen.findIndex((l) => l.includes(path) && (text == null || l.includes(text.slice(0, 40).replace(/\t/g, '\\t')) || l.includes(text.slice(0, 40))));
  if (i < 0) return '';
  const lines = [];
  for (let k = i - 1; k >= 0 && /^\s*\/\//.test(gen[k]); k--) lines.unshift(gen[k].trim().replace(/^\/\/\s?/, ''));
  if (lines.length === 0) {
    // (several edits under one comment: the nearest comment above)
    for (let k = i - 1; k >= 0 && k > i - 12; k--) if (/^\s*\/\//.test(gen[k])) { let a = k; while (a > 0 && /^\s*\/\//.test(gen[a - 1])) a--; for (let m = a; m <= k; m++) lines.push(gen[m].trim().replace(/^\/\/\s?/, '')); break; }
  }
  return lines.join(' ');
}

w('# Upstream sources: what cs2wasm changes');
w();
w('Generated by `node tools/upstream-report.mjs` from the manifests in `src/Cs2Wasm/Upstream` and dotnet/runtime v11.0.0');
w('(SPEC 7.5; docs/AUDIT.md A5.15). Everything not listed here is compiled as upstream wrote it. Not listed either:');
w('the trimmer\'s feature substitutions the manifests carry (`substitute` lines: a method body or a field value fixed');
w('for cs2wasm\'s features, as the IL trimmer fixes them), and the files under `Boundary/`, which are cs2wasm\'s own.');
w();
w('## Exact edits and replaced files, by library');
w();
for (const lib of readdirSync(upstream).sort()) {
  const m = join(upstream, lib, 'manifest.txt');
  if (!existsSync(m)) continue;
  const lines = lf(readFileSync(m, 'utf8')).split('\n');
  const edits = lines.filter((l) => l.startsWith('edit\t'));
  const replaced = lines.filter((l) => l.startsWith('replaced '));
  if (edits.length === 0 && replaced.length === 0) continue;
  w(`### ${lib}`);
  w();
  for (const r of replaced) {
    const p = r.slice('replaced '.length).trim();
    w(`- replaced: \`${p}\``);
    const why = reasonFor(p, null);
    if (why) w(`  - why: ${why}`);
  }
  for (const e of edits) {
    const [, p, text, repl] = e.split('\t');
    const short = (s) => (s.length > 110 ? s.slice(0, 107) + '...' : s).replace(/`/g, "'");
    w(`- edit: \`${p}\`: \`${short(text.trim())}\` becomes \`${short((repl ?? '').trim()) || '(nothing)'}\``);
    const why = reasonFor(p, text);
    if (why) w(`  - why: ${why}`);
  }
  w();
}

// System.Private.CoreLib's runtime half
const mine = join(upstream, 'System.Private.CoreLib', 'Runtime');
const theirs = join(runtime, 'src', 'mono', 'System.Private.CoreLib', 'src');
const files = [];
(function walk(d) { for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p); else if (n.endsWith('.cs')) files.push(p); } })(mine);
files.sort();
const same = [], own = [], changed = [];
for (const f of files) {
  const rel = relative(mine, f).replace(/\\/g, '/');
  const u = join(theirs, rel);
  if (!existsSync(u)) { own.push(rel); continue; }
  const a = lf(readFileSync(u, 'utf8')), b = lf(readFileSync(f, 'utf8'));
  if (a === b) { same.push(rel); continue; }
  const d = spawnSync('git', ['diff', '--no-index', '--numstat', '--ignore-cr-at-eol', u, f], { encoding: 'utf8' }).stdout.trim().split(/\s+/);
  const added = +d[0] || 0, removed = +d[1] || 0;
  // the reasons: the comments marked cs2wasm in the file
  const marks = b.split('\n').map((l) => l.trim()).filter((l) => /^(\/\/|\/\/\/|\*)/.test(l) && /cs2wasm/i.test(l))
    .map((l) => l.replace(/^\/\/\/?\s?/, '').replace(/<\/?[a-z]+>/g, ''));
  changed.push({ rel, added, removed, marks });
}
w('## System.Private.CoreLib: the runtime half');
w();
w(`Mono's runtime-specific files (\`src/mono/System.Private.CoreLib/src\`), which cs2wasm supplies against its own runtime`);
w(`(\`src/Cs2Wasm/Upstream/System.Private.CoreLib/Runtime\`): ${changed.length} changed, ${same.length} as upstream, ${own.length} cs2wasm's own.`);
w();
w('### Changed');
w();
changed.sort((x, y) => y.added + y.removed - (x.added + x.removed));
for (const c of changed) {
  w(`- \`${c.rel}\`: ${c.added} lines added, ${c.removed} removed`);
  for (const m of c.marks.slice(0, 6)) w(`  - ${m.length > 200 ? m.slice(0, 197) + '...' : m}`);
  if (c.marks.length > 6) w(`  - (and ${c.marks.length - 6} more comments marked cs2wasm in the file)`);
}
w();
w("### cs2wasm's own");
w();
for (const o of own) w(`- \`${o}\``);
w();
w('### As upstream');
w();
w(same.map((s) => '`' + s + '`').join(', '));
w();
writeFileSync(join(root, 'docs', 'UPSTREAM.md'), out.join('\n'));
console.log(`docs/UPSTREAM.md: ${changed.length} changed, ${same.length} as upstream, ${own.length} own`);
