using System.Text;
using System.Xml.Linq;

// CoreLibManifest resx <Strings.resx> <out.cs>: the SR properties, as constant strings (no resource lookup at run
// time: the library is built for one culture, invariant, so the English text is the text).
static class Resx
{
    public static int Run(string resx, string output)
    {
        var doc = XDocument.Load(resx);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> from dotnet/runtime's System.Private.CoreLib Strings.resx by tools/CoreLibManifest </auto-generated>");
        sb.AppendLine("namespace System");
        sb.AppendLine("{");
        sb.AppendLine("    internal static partial class SR");
        sb.AppendLine("    {");
        // what the resx generator also gives SR (reached only by a lookup of a key that is not one of the constants)
        sb.AppendLine("        private static global::System.Resources.ResourceManager s_resourceManager;");
        sb.AppendLine("        internal static global::System.Resources.ResourceManager ResourceManager => s_resourceManager ?? (s_resourceManager = new global::System.Resources.ResourceManager(typeof(SR)));");
        int n = 0;
        foreach (var d in doc.Root!.Elements("data"))
        {
            var name = (string?)d.Attribute("name");
            var value = (string?)d.Element("value") ?? "";
            if (name == null || d.Attribute("type") != null) continue;
            sb.AppendLine($"        internal static string @{name} => @\"{value.Replace("\"", "\"\"")}\";");
            n++;
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");
        Directory.CreateDirectory(Path.GetDirectoryName(output)!);
        File.WriteAllText(output, sb.ToString());
        Console.WriteLine($"{n} strings");
        return 0;
    }
}
