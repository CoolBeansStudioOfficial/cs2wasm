using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

// The implementation parts of a library's `[LibraryImport]` partial methods that cs2wasm's boundary
// (<upstream-dir>/<Library>/Boundary) does not implement. The module has no native libraries (SPEC section 8), so each
// is marked with the capability it needs: reaching one is a build error naming it, never a silent stub. Written to
// <upstream-dir>/<Library>/Generated/Interop.Unavailable.g.cs.
static class Externs
{
    public static CSharpCompilation Run(string root, string upstream, string lib, IReadOnlyDictionary<string, CSharpCompilation> built)
    {
        var output = Path.Combine(upstream, lib, "Generated", "Interop.Unavailable.g.cs");
        var comp = Check.Compile(root, upstream, lib, built, exclude: output);
        var missing = comp.GetDiagnostics().Where(d => d.Id == "CS8795").ToList();
        var byType = new SortedDictionary<string, (INamedTypeSymbol Type, List<string> Methods)>(StringComparer.Ordinal);
        foreach (var d in missing)
        {
            var tree = d.Location.SourceTree!;
            var decl = tree.GetRoot().FindNode(d.Location.SourceSpan).FirstAncestorOrSelf<MethodDeclarationSyntax>();
            if (decl == null) continue;
            var m = comp.GetSemanticModel(tree).GetDeclaredSymbol(decl)!;
            var li = m.GetAttributes().FirstOrDefault(a => a.AttributeClass?.Name is "LibraryImportAttribute" or "DllImportAttribute");
            var native = li?.ConstructorArguments.FirstOrDefault().Value as string ?? "?";
            var entry = li?.NamedArguments.FirstOrDefault(a => a.Key == "EntryPoint").Value.Value as string ?? m.Name;
            var key = m.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (!byType.TryGetValue(key, out var e)) byType[key] = e = (m.ContainingType, []);
            e.Methods.Add(Method(m, decl.Modifiers.Any(SyntaxKind.UnsafeKeyword), $"platform invoke ({native}!{entry})"));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> by tools/CoreLibManifest externs: the library's platform invokes that cs2wasm's boundary does not");
        sb.AppendLine("// implement. The module has no native libraries; reaching one of these is a build error naming it. </auto-generated>");
        sb.AppendLine("#pragma warning disable CS8826 // partial declarations' parameter names differ");
        int n = 0;
        foreach (var (_, (type, methods)) in byType)
        {
            var chain = new List<INamedTypeSymbol>();
            for (var t = type; t != null; t = t.ContainingType) chain.Insert(0, t);
            var ns = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString();
            if (ns != null) sb.AppendLine($"namespace {ns} {{");
            foreach (var t in chain)
            {
                var kind = t.TypeKind == TypeKind.Struct ? "struct" : t.TypeKind == TypeKind.Interface ? "interface" : "class";
                var tps = t.TypeParameters.Length == 0 ? "" : "<" + string.Join(", ", t.TypeParameters.Select(p => p.Name)) + ">";
                sb.AppendLine($"unsafe {(t.IsRefLikeType ? "ref " : "")}partial {kind} {t.Name}{tps} {{");
            }
            foreach (var m in methods) { sb.AppendLine(m); n++; }
            foreach (var _ in chain) sb.AppendLine("}");
            if (ns != null) sb.AppendLine("}");
        }
        if (n == 0) { if (File.Exists(output)) File.Delete(output); return comp; }
        Directory.CreateDirectory(Path.GetDirectoryName(output)!);
        File.WriteAllText(output, sb.ToString());
        Console.WriteLine($"{lib}: {n} unavailable platform invokes");
        return Check.Compile(root, upstream, lib, built);
    }

    static readonly SymbolDisplayFormat Fq = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions | SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    static string Method(IMethodSymbol m, bool isUnsafe, string capability)
    {
        var access = m.DeclaredAccessibility switch
        {
            Accessibility.Public => "public", Accessibility.Internal => "internal", Accessibility.Private => "private",
            Accessibility.Protected => "protected", Accessibility.ProtectedOrInternal => "protected internal", _ => "private protected",
        };
        var ps = string.Join(", ", m.Parameters.Select(p =>
            (p.ScopedKind == ScopedKind.ScopedRef ? "scoped " : "") +
            (p.RefKind switch { RefKind.Ref => "ref ", RefKind.Out => "out ", RefKind.In => "in ", RefKind.RefReadOnlyParameter => "ref readonly ", _ => "" })
            + p.Type.ToDisplayString(Fq) + " @" + p.Name));
        var ret = (m.ReturnsByRef ? "ref " : m.ReturnsByRefReadonly ? "ref readonly " : "") + (m.ReturnsVoid ? "void" : m.ReturnType.ToDisplayString(Fq));
        var lit = capability.Replace("\\", "\\\\").Replace("\"", "\\\"");
        return $"    [global::Cs2Wasm.Runtime.MissingCapability(\"{lit}\")]\n    {access} {(m.IsStatic ? "static " : "")}{(isUnsafe ? "unsafe " : "")}partial {ret} {m.Name}({ps}) => throw new global::System.PlatformNotSupportedException();";
    }
}
