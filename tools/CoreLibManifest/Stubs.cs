using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

// CoreLibManifest stubs <ref-pack-dir> <upstream-dir> <library> <capability> <assembly.dll> [namespace or type prefix...]:
// a library cs2wasm does not build from source, as declarations: the public API of a .NET reference assembly (the
// types under the prefixes), every member a [MissingCapability]: a program that reaches one fails to build, naming the
// capability (section 8). Written to <upstream-dir>/<library>/ (manifest.txt and Generated/Stubs.g.cs).
static class Stubs
{
    static readonly SymbolDisplayFormat Fq = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.UseSpecialTypes | SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier)
        .WithGenericsOptions(SymbolDisplayGenericsOptions.IncludeTypeParameters);

    public static int Run(string refDir, string upstream, string lib, string capability, string dll, string[] prefixes)
    {
        var refs = Directory.GetFiles(refDir, "*.dll").Select(f => (MetadataReference)MetadataReference.CreateFromFile(f)).ToList();
        var comp = CSharpCompilation.Create("probe", [], refs);
        var target = Path.GetFileNameWithoutExtension(dll);
        var asm = comp.SourceModule.ReferencedAssemblySymbols.FirstOrDefault(a => a.Name == target) ?? throw new Exception("no assembly " + target);
        var sb = new StringBuilder();
        sb.AppendLine($"// <auto-generated> by tools/CoreLibManifest stubs from the .NET reference assembly {target}: its public API, every member");
        sb.AppendLine($"// needing {capability}, which cs2wasm does not have: reaching one is a build error naming it. </auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS0067, CS0108, CS0114, CS0169, CS0414, CS0649, CS0659, CS0660, CS0661, CS0809, CS8597, CS8618, CS8765, CS8767");
        int n = 0;
        foreach (var ns in AllNamespaces(asm.GlobalNamespace))
        {
            var types = ns.GetTypeMembers().Where(t => t.DeclaredAccessibility == Accessibility.Public && Wanted(t, prefixes)).OrderBy(t => t.MetadataName, StringComparer.Ordinal).ToList();
            if (types.Count == 0) continue;
            sb.AppendLine($"namespace {ns.ToDisplayString()}");
            sb.AppendLine("{");
            foreach (var t in types) { Type(sb, t, "    ", capability); n++; }
            sb.AppendLine("}");
        }
        var dir = Path.Combine(upstream, lib);
        Directory.CreateDirectory(Path.Combine(dir, "Generated"));
        File.WriteAllText(Path.Combine(dir, "Generated", "Stubs.g.cs"), sb.ToString());
        File.WriteAllText(Path.Combine(dir, "manifest.txt"),
            $"# {lib} for cs2wasm: generated by tools/CoreLibManifest stubs from the reference assembly {target} ({string.Join(", ", prefixes)}).\n" +
            $"# Declarations only: reaching a member is a build error ({capability}).\ndefine NET\ndefine NETCOREAPP\n");
        Console.WriteLine($"{lib}: {n} types from {target}");
        return 0;
    }

    static bool Wanted(INamedTypeSymbol t, string[] prefixes)
    {
        var name = t.ToDisplayString();
        return prefixes.Length == 0 || prefixes.Any(p => name == p || name.StartsWith(p + ".") || name.StartsWith(p + "<"));
    }

    static IEnumerable<INamespaceSymbol> AllNamespaces(INamespaceSymbol ns)
    {
        yield return ns;
        foreach (var c in ns.GetNamespaceMembers().OrderBy(n => n.Name, StringComparer.Ordinal))
            foreach (var x in AllNamespaces(c)) yield return x;
    }

    static string T(ITypeSymbol t) => t.ToDisplayString(Fq);

    static string Access(ISymbol s) => s.DeclaredAccessibility switch
    {
        Accessibility.Public => "public",
        Accessibility.Protected => "protected",
        Accessibility.ProtectedOrInternal => "protected internal",
        Accessibility.ProtectedAndInternal => "private protected",
        Accessibility.Internal => "internal",
        _ => "private",
    };

    static bool Visible(ISymbol s) => s.DeclaredAccessibility is Accessibility.Public or Accessibility.Protected or Accessibility.ProtectedOrInternal;

    static string TypeParams(ImmutableArrayWrapper<ITypeParameterSymbol> tps) => tps.Count == 0 ? "" : "<" + string.Join(", ", tps.Items.Select(p => (p.Variance == VarianceKind.Out ? "out " : p.Variance == VarianceKind.In ? "in " : "") + p.Name)) + ">";

    readonly record struct ImmutableArrayWrapper<TItem>(IReadOnlyList<TItem> Items) { public int Count => Items.Count; }

    static string Constraints(IEnumerable<ITypeParameterSymbol> tps)
    {
        var sb = new StringBuilder();
        foreach (var p in tps)
        {
            var cs = new List<string>();
            if (p.HasReferenceTypeConstraint) cs.Add("class");
            if (p.HasUnmanagedTypeConstraint) cs.Add("unmanaged");
            else if (p.HasValueTypeConstraint) cs.Add("struct");
            if (p.HasNotNullConstraint) cs.Add("notnull");
            cs.AddRange(p.ConstraintTypes.Select(T));
            if (p.HasConstructorConstraint && !p.HasValueTypeConstraint) cs.Add("new()");
            if (p.AllowsRefLikeType) cs.Add("allows ref struct");
            if (cs.Count > 0) sb.Append(" where ").Append(p.Name).Append(" : ").Append(string.Join(", ", cs));
        }
        return sb.ToString();
    }

    static string Params(IEnumerable<IParameterSymbol> ps) => string.Join(", ", ps.Select(p =>
    {
        var s = new StringBuilder();
        if (p.IsParams) s.Append("params ");
        s.Append(p.RefKind switch { RefKind.Ref => "ref ", RefKind.Out => "out ", RefKind.In => "in ", RefKind.RefReadOnlyParameter => "ref readonly ", _ => "" });
        if (p.ScopedKind == ScopedKind.ScopedRef && p.RefKind != RefKind.Out) s.Insert(0, "scoped ");
        s.Append(T(p.Type)).Append(' ').Append(SyntaxFacts.GetKeywordKind(p.Name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? "@" + p.Name : p.Name);
        if (p.HasExplicitDefaultValue) s.Append(" = default!");
        return s.ToString();
    }));

    static string Body(string cap, bool hasOut, IEnumerable<IParameterSymbol> ps) => " => throw null!;";

    static void Type(StringBuilder sb, INamedTypeSymbol t, string ind, string cap)
    {
        var tps = new ImmutableArrayWrapper<ITypeParameterSymbol>(t.TypeParameters);
        if (t.TypeKind == TypeKind.Enum)
        {
            if (t.GetAttributes().Any(a => a.AttributeClass?.Name == "FlagsAttribute")) sb.AppendLine(ind + "[global::System.Flags]");
            sb.AppendLine($"{ind}{Access(t)} enum {t.Name} : {T(t.EnumUnderlyingType!)}");
            sb.AppendLine(ind + "{");
            foreach (var f in t.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
                sb.AppendLine($"{ind}    {f.Name} = unchecked(({T(t.EnumUnderlyingType!)}){Convert.ToString(f.ConstantValue, System.Globalization.CultureInfo.InvariantCulture)}),");
            sb.AppendLine(ind + "}");
            return;
        }
        if (t.TypeKind == TypeKind.Delegate)
        {
            var inv = t.DelegateInvokeMethod!;
            sb.AppendLine($"{ind}{Access(t)} delegate {Ret(inv)} {t.Name}{TypeParams(tps)}({Params(inv.Parameters)}){Constraints(t.TypeParameters)};");
            return;
        }
        var kind = t.TypeKind switch { TypeKind.Interface => "partial interface", TypeKind.Struct => (t.IsReadOnly ? "readonly " : "") + (t.IsRefLikeType ? "ref " : "") + "partial struct", _ => "partial class" };
        var mods = t.TypeKind == TypeKind.Class ? (t.IsStatic ? "static " : t.IsAbstract ? "abstract " : t.IsSealed ? "sealed " : "") : "";
        var bases = new List<string>();
        if (t.TypeKind == TypeKind.Class && t.BaseType is { } bt && bt.SpecialType != SpecialType.System_Object) bases.Add(T(bt));
        bases.AddRange(t.Interfaces.Select(T));
        sb.AppendLine($"{ind}{Access(t)} {mods}unsafe {kind} {t.Name}{TypeParams(tps)}{(bases.Count > 0 ? " : " + string.Join(", ", bases) : "")}{Constraints(t.TypeParameters)}");
        sb.AppendLine(ind + "{");
        var mi = ind + "    ";
        bool iface = t.TypeKind == TypeKind.Interface;
        var attr = $"[global::Cs2Wasm.Runtime.MissingCapability(\"{cap}\")] ";
        // a constructor for derived types to chain to (reference assemblies hide the internal ones)
        if (t.TypeKind == TypeKind.Class && !t.IsStatic && !t.InstanceConstructors.Any(c => Visible(c) && c.Parameters.Length == 0))
            sb.AppendLine($"{mi}internal {t.Name}(){BaseCall(t)} {{ }}");
        foreach (var m in t.GetMembers().Where(m => Visible(m) || m is IMethodSymbol { MethodKind: MethodKind.ExplicitInterfaceImplementation } || m is IPropertySymbol { ExplicitInterfaceImplementations.Length: > 0 } || iface))
        {
            switch (m)
            {
                case IFieldSymbol f when !f.IsImplicitlyDeclared:
                    if (f.HasConstantValue) sb.AppendLine($"{mi}{Access(f)} const {T(f.Type)} {f.Name} = {Literal(f)};");
                    else sb.AppendLine($"{mi}{Access(f)} {(f.IsStatic ? "static " : "")}{(f.IsReadOnly ? "readonly " : "")}{T(f.Type)} {f.Name}{(f.IsStatic || t.TypeKind != TypeKind.Struct ? " = default!" : "")};");
                    break;
                case IMethodSymbol { MethodKind: MethodKind.Constructor } c when !c.IsImplicitlyDeclared:
                    if (t.TypeKind == TypeKind.Struct && c.Parameters.Length == 0) break;
                    sb.AppendLine($"{mi}{attr}{Access(c)} {t.Name}({Params(c.Parameters)}){(t.TypeKind == TypeKind.Class ? BaseCall(t) : "")} {{ throw null!; }}");
                    break;
                case IMethodSymbol { MethodKind: MethodKind.Ordinary or MethodKind.UserDefinedOperator or MethodKind.Conversion or MethodKind.ExplicitInterfaceImplementation } om:
                    {
                        string name = om.MethodKind switch
                        {
                            MethodKind.UserDefinedOperator => "operator " + OperatorToken(om.Name),
                            MethodKind.Conversion => "",
                            MethodKind.ExplicitInterfaceImplementation => T(om.ExplicitInterfaceImplementations[0].ContainingType) + "." + om.ExplicitInterfaceImplementations[0].Name,
                            _ => om.Name,
                        };
                        var head = om.MethodKind == MethodKind.Conversion
                            ? $"{Access(om)} static {(om.Name == "op_Explicit" ? "explicit" : "implicit")} operator {T(om.ReturnType)}"
                            : om.MethodKind == MethodKind.ExplicitInterfaceImplementation ? $"{Ret(om)} {name}" : $"{(iface && !om.IsStatic ? "" : Access(om) + " ")}{Modifiers(om, iface)}{Ret(om)} {name}";
                        var tpl = om.TypeParameters.Length == 0 ? "" : "<" + string.Join(", ", om.TypeParameters.Select(p => p.Name)) + ">";
                        bool abs = om.IsAbstract;
                        var cons = om.MethodKind is MethodKind.ExplicitInterfaceImplementation || om.IsOverride ? OverrideConstraints(om.TypeParameters) : Constraints(om.TypeParameters);
                        sb.AppendLine($"{mi}{(abs ? "" : attr)}{head}{tpl}({Params(om.Parameters)}){cons}{(abs ? ";" : " => throw null!;")}");
                        break;
                    }
                case IPropertySymbol p:
                    {
                        string name = p.ExplicitInterfaceImplementations.Length > 0 ? T(p.ExplicitInterfaceImplementations[0].ContainingType) + "." + (p.IsIndexer ? "this" : p.ExplicitInterfaceImplementations[0].Name)
                            : p.IsIndexer ? "this" : p.Name;
                        var idx = p.IsIndexer ? "[" + Params(p.Parameters) + "]" : "";
                        var head = p.ExplicitInterfaceImplementations.Length > 0 ? "" : (iface && !p.IsStatic ? "" : Access(p) + " ") + Modifiers(p, iface);
                        var refk = p.ReturnsByRef ? "ref " : p.ReturnsByRefReadonly ? "ref readonly " : "";
                        bool abs = p.IsAbstract;
                        var acc = new StringBuilder();
                        if (p.GetMethod is { } g && (Visible(g) || iface || p.ExplicitInterfaceImplementations.Length > 0)) acc.Append(abs ? "get; " : attr + (g.DeclaredAccessibility != p.DeclaredAccessibility && p.ExplicitInterfaceImplementations.Length == 0 ? Access(g) + " " : "") + "get => throw null!; ");
                        if (p.SetMethod is { } st && (Visible(st) || iface || p.ExplicitInterfaceImplementations.Length > 0)) acc.Append(abs ? (st.IsInitOnly ? "init; " : "set; ") : attr + (st.DeclaredAccessibility != p.DeclaredAccessibility && p.ExplicitInterfaceImplementations.Length == 0 ? Access(st) + " " : "") + (st.IsInitOnly ? "init" : "set") + " => throw null!; ");
                        // (an indexer with another name than Item: XmlNodeList's ItemOf, beside its Item method)
                        if (p.IsIndexer && p.ExplicitInterfaceImplementations.Length == 0 && p.MetadataName != "Item") sb.AppendLine($"{mi}[global::System.Runtime.CompilerServices.IndexerName(\"{p.MetadataName}\")]");
                        sb.AppendLine($"{mi}{head}{refk}{T(p.Type)} {name}{idx} {{ {acc}}}");
                        break;
                    }
                case IEventSymbol e:
                    {
                        var head = e.ExplicitInterfaceImplementations.Length > 0 ? "" : (iface && !e.IsStatic ? "" : Access(e) + " ") + Modifiers(e, iface);
                        var name = e.ExplicitInterfaceImplementations.Length > 0 ? T(e.ExplicitInterfaceImplementations[0].ContainingType) + "." + e.Name : e.Name;
                        if (e.IsAbstract) sb.AppendLine($"{mi}{head}event {T(e.Type)} {name};");
                        else sb.AppendLine($"{mi}{head}event {T(e.Type)} {name} {{ {attr}add {{ }} {attr}remove {{ }} }}");
                        break;
                    }
                case INamedTypeSymbol nt when Visible(nt):
                    Type(sb, nt, mi, cap);
                    break;
            }
        }
        sb.AppendLine(ind + "}");
    }

    static string OverrideConstraints(IEnumerable<ITypeParameterSymbol> tps)
    {
        var sb = new StringBuilder();
        foreach (var p in tps)
        {
            if (p.HasReferenceTypeConstraint) sb.Append(" where ").Append(p.Name).Append(" : class");
            else if (p.HasValueTypeConstraint) sb.Append(" where ").Append(p.Name).Append(" : struct");
        }
        return sb.ToString();
    }

    static string BaseCall(INamedTypeSymbol t)
    {
        var b = t.BaseType;
        if (b == null || b.SpecialType == SpecialType.System_Object) return "";
        var ctors = b.InstanceConstructors.Where(c => c.DeclaredAccessibility != Accessibility.Private).OrderBy(c => c.Parameters.Length).ToList();
        if (ctors.Count == 0 || ctors[0].Parameters.Length == 0) return "";
        // (stub constructors never run: any arguments do)
        return " : base(" + string.Join(", ", ctors[0].Parameters.Select(p => "default(" + T(p.Type) + ")!")) + ")";
    }

    static string Ret(IMethodSymbol m) => (m.ReturnsByRef ? "ref " : m.ReturnsByRefReadonly ? "ref readonly " : "") + (m.ReturnsVoid ? "void" : T(m.ReturnType));

    static string Modifiers(ISymbol m, bool iface)
    {
        var sb = new StringBuilder();
        if (m.IsStatic) sb.Append("static ");
        if (iface) { if (m.IsStatic && m.IsAbstract) sb.Append("abstract "); return sb.ToString(); }
        if (m.IsAbstract) sb.Append("abstract ");
        else if (m.IsOverride) sb.Append(m.IsSealed ? "sealed override " : "override ");
        else if (m.IsVirtual) sb.Append("virtual ");
        return sb.ToString();
    }

    static string Literal(IFieldSymbol f) => f.ConstantValue switch
    {
        null => "null",
        string s => SymbolDisplay.FormatLiteral(s, true),
        char c => SymbolDisplay.FormatLiteral(c, true),
        bool b => b ? "true" : "false",
        float x => float.IsNaN(x) ? "float.NaN" : float.IsPositiveInfinity(x) ? "float.PositiveInfinity" : float.IsNegativeInfinity(x) ? "float.NegativeInfinity" : x.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "f",
        double x => double.IsNaN(x) ? "double.NaN" : double.IsPositiveInfinity(x) ? "double.PositiveInfinity" : double.IsNegativeInfinity(x) ? "double.NegativeInfinity" : x.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "d",
        decimal x => x.ToString(System.Globalization.CultureInfo.InvariantCulture) + "m",
        var v when f.Type.TypeKind == TypeKind.Enum => "unchecked((" + T(f.Type) + ")" + Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture) + ")",
        var v => "unchecked((" + T(f.Type) + ")" + Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture) + ")",
    };

    static string OperatorToken(string name) => name switch
    {
        "op_Addition" => "+", "op_Subtraction" => "-", "op_Multiply" => "*", "op_Division" => "/", "op_Modulus" => "%",
        "op_Equality" => "==", "op_Inequality" => "!=", "op_LessThan" => "<", "op_GreaterThan" => ">", "op_LessThanOrEqual" => "<=",
        "op_GreaterThanOrEqual" => ">=", "op_BitwiseAnd" => "&", "op_BitwiseOr" => "|", "op_ExclusiveOr" => "^", "op_LeftShift" => "<<",
        "op_RightShift" => ">>", "op_UnaryNegation" => "-", "op_UnaryPlus" => "+", "op_LogicalNot" => "!", "op_OnesComplement" => "~",
        "op_Increment" => "++", "op_Decrement" => "--", "op_True" => "true", "op_False" => "false",
        _ => throw new Exception("operator " + name),
    };
}
