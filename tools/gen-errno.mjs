// node tools/gen-errno.mjs <runtime-dir> <emscripten-dir> > src/Il2Wasm/Upstream/System.Private.CoreLib/Boundary/Natives/Errno.g.cs
//
// The browser runtime's errno, as libSystem.Native built with Emscripten has it: Emscripten's errno numbers
// (system/lib/libc/musl/arch/emscripten/bits/errno.h over wasi/api.h), System.Native's two conversions
// (src/native/libs/Common/pal_error_common.h, with its #ifdefs evaluated for Emscripten), the PAL values
// (src/libraries/Common/src/Interop/Unix/Interop.Errors.cs) and musl's messages as Emscripten builds strerror
// (system/lib/libc/musl/src/errno/__strerror.h; unknown codes "Unknown error").
// <runtime-dir>: a dotnet/runtime checkout at v11.0.0; <emscripten-dir>: emscripten-core/emscripten at the version
// src/mono/browser/emscripten-version.txt names (6.0.2).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const [rt, em] = process.argv.slice(2);
const read = (d, f) => readFileSync(join(d, f), 'utf8');

// Emscripten's errno names
const wasi = {};
for (const m of read(em, 'system/include/wasi/api.h').matchAll(/#define __WASI_ERRNO_(\w+) \(UINT16_C\((\d+)\)\)/g)) wasi['__WASI_ERRNO_' + m[1]] = +m[2];
const errnoDefs = {};
for (const m of read(em, 'system/lib/libc/musl/arch/emscripten/bits/errno.h').matchAll(/#define\s+(E\w+)\s+(\w+)/g)) errnoDefs[m[1]] = m[2];
const errno = {};
const value = n => {
  if (n in errno) return errno[n];
  const d = errnoDefs[n];
  if (d === undefined) return undefined;
  const v = /^\d+$/.test(d) ? +d : d in wasi ? wasi[d] : value(d);
  return (errno[n] = v);
};
for (const n of Object.keys(errnoDefs)) value(n);

// the PAL's values
const pal = {};
for (const m of read(rt, 'src/native/libs/Common/pal_error_common.h').matchAll(/^\s*Error_(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+),/gm)) pal[m[1]] = Number(m[2]);
// (the enum's aliases: `Error_EWOULDBLOCK = Error_EAGAIN,`)
for (const m of read(rt, 'src/native/libs/Common/pal_error_common.h').matchAll(/^\s*Error_(\w+)\s*=\s*Error_(\w+),/gm)) pal[m[1]] = pal[m[2]];

// (pal_error_common.h's own two: `#define EHOSTNOTFOUND (-Error_EHOSTNOTFOUND)`, ESOCKETERROR likewise)
errno.EHOSTNOTFOUND = -pal.EHOSTNOTFOUND;
errno.ESOCKETERROR = -pal.ESOCKETERROR;

// one of pal_error_common.h's switches, with its preprocessor lines evaluated
function cases(text, fn) {
  const body = text.slice(text.indexOf('inline static int32_t ' + fn));
  const lines = body.slice(0, body.indexOf('\n}\n')).split('\n');
  const out = [];
  const stack = [];
  let pending = [];
  const on = () => stack.every(x => x);
  for (const raw of lines) {
    const l = raw.trim();
    let m;
    if ((m = l.match(/^#ifdef (\w+)/))) { stack.push(value(m[1]) !== undefined); continue; }
    if ((m = l.match(/^#if (\w+) != (\w+)/))) { stack.push(value(m[1]) !== value(m[2])); continue; }
    if (l.startsWith('#endif')) { stack.pop(); continue; }
    if (l.startsWith('#')) throw new Error('unhandled: ' + l);
    if (!on()) continue;
    if ((m = l.match(/^case (\w+):/))) { pending.push(m[1]); continue; }
    if ((m = l.match(/^return (-?\w+);/)) && pending.length) { for (const c of pending) out.push([c, m[1]]); pending = []; continue; }
    if (l.startsWith('break;') || l.startsWith('default:')) pending = [];
  }
  return out;
}
const common = read(rt, 'src/native/libs/Common/pal_error_common.h');
const num = n => n === '0' ? 0 : n.startsWith('Error_') ? pal[n.slice(6)] : value(n);
const toPal = cases(common, 'ConvertErrorPlatformToPal').map(([c, r]) => [num(c), num(r), c, r]);
const toPlatform = cases(common, 'ConvertErrorPalToPlatform').map(([c, r]) => [num(c), num(r), c, r]);
for (const [a, b, c, r] of [...toPal, ...toPlatform]) if (a === undefined || b === undefined) throw new Error(`unresolved ${c} -> ${r}`);

// musl's messages, as Emscripten's strerror indexes them
const msgs = new Map();
for (const m of read(em, 'system/lib/libc/musl/src/errno/__strerror.h').matchAll(/^E\((\w+),\s*"([^"]*)"\)/gm)) {
  const n = m[1] === '0' ? 0 : value(m[1]);
  if (n === undefined) throw new Error('message for unknown ' + m[1]);
  if (!msgs.has(n)) msgs.set(n, m[2]);
}
// (the first entry in the file is Emscripten's "Success" for 0)
const head = read(em, 'system/lib/libc/musl/src/errno/__strerror.h');
const em0 = head.match(/#if defined\(__EMSCRIPTEN__\)[\s\S]*?E\(0,\s*"([^"]*)"\)/)[1];
msgs.set(0, em0);

const q = s => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const seen = new Set();
const o = [];
o.push('// <auto-generated> by tools/gen-errno.mjs from dotnet/runtime v11.0.0 (pal_error_common.h, Interop.Errors.cs) and');
o.push('// Emscripten 6.0.2 (bits/errno.h, wasi/api.h, musl\'s __strerror.h): the browser runtime\'s errno. </auto-generated>');
o.push('namespace Il2Wasm.Runtime.Natives');
o.push('{');
o.push('    internal static class Errno');
o.push('    {');
o.push('        /// <summary>SystemNative_ConvertErrorPlatformToPal: an Emscripten errno to its PAL code (ENONSTANDARD otherwise).</summary>');
o.push('        public static int PlatformToPal(int platformErrno) => platformErrno switch');
o.push('        {');
for (const [a, b, c, r] of toPal) { if (seen.has(a)) continue; seen.add(a); o.push(`            ${a} => ${b}, // ${c} -> ${r}`); }
o.push(`            _ => ${pal['ENONSTANDARD']},`);
o.push('        };');
o.push('');
o.push('        /// <summary>SystemNative_ConvertErrorPalToPlatform: a PAL code to the Emscripten errno (-1 for one it does not know).</summary>');
o.push('        public static int PalToPlatform(int error) => error switch');
o.push('        {');
seen.clear();
for (const [a, b, c, r] of toPlatform) { if (seen.has(a)) continue; seen.add(a); o.push(`            ${a} => ${b}, // ${c} -> ${r}`); }
o.push('            _ => -1,');
o.push('        };');
o.push('');
o.push('        /// <summary>Emscripten\'s strerror: musl\'s message, "Unknown error" for a code it has none for.</summary>');
o.push('        public static string Message(int platformErrno) => platformErrno switch');
o.push('        {');
for (const [n, s] of [...msgs].sort((x, y) => x[0] - y[0])) o.push(`            ${n} => ${q(s)},`);
o.push('            _ => "Unknown error",');
o.push('        };');
o.push('');
o.push('        // Emscripten\'s errno numbers that the runtime sets');
for (const n of Object.keys(errno).sort()) o.push(`        public const int ${n} = ${errno[n]};`);
o.push('    }');
o.push('}');
process.stdout.write(o.join('\n') + '\n');
